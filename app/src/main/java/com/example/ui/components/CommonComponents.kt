fun formatFileSize(bytes: Long): String {
    if (bytes <= 0) return "0 B"
    val units = arrayOf("B", "KB", "MB", "GB")
    val digitGroups = (Math.log10(bytes.toDouble()) / Math.log10(1024.0)).toInt().coerceIn(0, 3)
    return String.format(Locale.US, "%.1f %s", bytes / Math.pow(1024.0, digitGroups.toDouble()), units[digitGroups])
}

fun formatTimestamp(millis: Long): String {
    val sdf = SimpleDateFormat("dd MMM, hh:mm a", Locale.getDefault())
    return sdf.format(Date(millis))
}

@Composable
fun FormatBadge(
    format: String,
    modifier: Modifier = Modifier
) {
    val isApk = format.equals("APK", ignoreCase = true)
    val bgColor = if (isApk) EmeraldSuccessDark.copy(alpha = 0.18f) else OrangeSecondaryDark.copy(alpha = 0.18f)
    val textColor = if (isApk) EmeraldSuccessDark else OrangeSecondaryDark

    Surface(
        modifier = modifier.clip(RoundedCornerShape(6.dp)),
        color = bgColor
    ) {
        Text(
            text = format.uppercase(),
            color = textColor,
            fontSize = 11.sp,
            fontWeight = FontWeight.Bold,
            modifier = Modifier.padding(horizontal = 8.dp, vertical = 3.dp)
        )
    }
}

